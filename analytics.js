// Аналитика Umami (cloud.umami.is): скрипт подключён в index.html, здесь — события.
// Сайт одностраничный, адрес при открытии купюры не меняется, поэтому каждая страница купюры
// отправляется как отдельный «просмотр» с адресом /#<id> — в Umami она видна как своя страница.
// Если скрипт заблокирован (блокировщик рекламы) или ещё не загрузился, вызовы молча пропускаются.

const umami = () => window.umami;

export function track(name, data) {
  try { umami()?.track(name, data); } catch { /* аналитика не должна ломать сайт */ }
}

// Виртуальный просмотр страницы купюры
export function trackNote(id, title) {
  try {
    umami()?.track((props) => ({ ...props, url: `/#${id}`, title }));
  } catch { /* см. выше */ }
}
